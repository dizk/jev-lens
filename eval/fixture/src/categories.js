/** Normalize a user-supplied category to its canonical name, or return the input trimmed and lowercased. */
export function normalizeCategory(input) {
	const key = String(input ?? "").trim().toLowerCase();
	if (!key) return "";
	return ALIASES[key] ?? key;
}

/** Group categories into reporting sections. */
export const SECTIONS = {
	essentials: ["rent", "utilities", "food", "health"],
	lifestyle: ["entertainment", "clothing", "travel", "gifts", "subscriptions"],
	other: ["transport", "education", "household"],
};

export function sectionOf(category) {
	for (const [section, cats] of Object.entries(SECTIONS)) if (cats.includes(category)) return section;
	return "other";
}
